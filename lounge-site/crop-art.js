// ---------- 色 ----------
const hex = (c) => [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
const toHex = (a) => "#" + a.map((x) => Math.max(0, Math.min(255, Math.round(x))).toString(16).padStart(2, "0")).join("");
const mix = (c, to, k) => { const a = hex(c), b = hex(to); return toHex(a.map((x, i) => x + (b[i] - x) * k)); };
const LEAF = "#5DAE4B";
const FIXED = { o: "#272241", b: "#8A6440", B: "#5E4129", w: "#FFFFFF" };
const GOLD = ["#F2C94C", "#FFF1A8", "#B8862A"];
const hsl = (h, s, l) => { const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l), f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1)); return toHex([f(0) * 255, f(8) * 255, f(4) * 255]); };
// 文字 → 色。row は 虹色の ときだけ 使う（行ごとに 色が まわる）
export function palette(look, variant, row = 0) {
  const [m, s] = look.c, leaf = look.leaf || LEAF;
  let main = [m, mix(m, "#FFFFFF", 0.4), mix(m, "#000000", 0.35)];
  if (variant === "gold") main = GOLD;
  if (variant === "rainbow") { const c = hsl((row * 26) % 360, 0.85, 0.6); main = [c, mix(c, "#FFFFFF", 0.45), mix(c, "#000000", 0.3)]; }
  return { ...FIXED, m: main[0], n: main[1], M: main[2], s, t: mix(s, "#FFFFFF", 0.4), S: mix(s, "#000000", 0.35), g: leaf, h: mix(leaf, "#FFFFFF", 0.35), G: mix(leaf, "#000000", 0.35) };
}

// 作物の その 段の 絵の 行（16 行の 文字列）
export function gridOf(crop, stage) {
  const u = CROP_ART[crop.id] || {}, f = FORMS[crop.look.form] || {};   // 作物ごとの 絵が あれば それ、なければ 型
  if (stage === "sprout") return u.sprout || f.sprout || COMMON.sprout;
  if (stage === "over") return (crop.after && crop.after !== "flee" && (u.over || f.over)) || COMMON.dead;
  if (stage === "dead") return COMMON.dead;
  return u[stage] || f[stage] || GENERIC[stage];
}
// 絵の 色 → 16 × 16 の 配列（"#rrggbb" か null）。node でも 使える
export function cropPixels(crop, stage, variant) {
  const g = gridOf(crop, stage);
  return g.map((line, y) => { const p = palette(crop.look, variant, y); return [...line].map((ch) => (ch === "." ? null : p[ch] || null)); });
}
// 画面で 使う：canvas（scale 倍）。three.js の 板にも この canvas を 使う（CanvasTexture・NearestFilter）
export function cropCanvas(crop, stage, { variant, scale = 1 } = {}) {
  const px = cropPixels(crop, stage, variant), c = document.createElement("canvas"); c.width = c.height = 16 * scale;
  const x = c.getContext("2d");
  px.forEach((row, j) => row.forEach((col, i) => { if (col) { x.fillStyle = col; x.fillRect(i * scale, j * scale, scale, scale); } }));
  return c;
}
export const cropPic = (crop, stage, opt) => cropCanvas(crop, stage, opt).toDataURL();
